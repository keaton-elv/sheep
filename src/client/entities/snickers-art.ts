export const CENTER_COL = 15;

/** One layer of a pose: a part drawn at (dx, dy) inside the 32x32 frame. */
export type Layer = readonly [part: PartName, dx: number, dy: number];

// ---------- building ----------

const isClear = (ch: string | undefined) => ch === undefined || ch === "." || ch === " ";

/**
 * Rows -> canvas. Every transparent pixel touching a filled one (4-neighbourhood) becomes the
 * outline: charcoal beside grey points, warm brown beside cream, berry beside a lone tongue.
 */
export function buildSprite(rows: readonly string[], mask?: Uint8Array): HTMLCanvasElement {
  const h = rows.length;
  const w = Math.max(1, ...rows.map((r) => r.length));
  const c = document.createElement("canvas");
  c.width = w;
  c.height = Math.max(1, h);
  const ctx = c.getContext("2d");
  const at = (x: number, y: number): string | undefined => (y < 0 || y >= h ? undefined : rows[y]![x]);
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const ch = at(x, y);
      let color: string | undefined;
      if (isClear(ch)) {
        let point = false;
        let cream = false;
        let tongue = false;
        for (const [nx, ny] of [
          [x + 1, y],
          [x - 1, y],
          [x, y + 1],
          [x, y - 1],
        ] as const) {
          const n = at(nx, ny);
          if (isClear(n) || OUTLINE_CHARS.includes(n!)) continue;
          if (POINT_MATS.includes(n!)) point = true;
          else if (TONGUE_MATS.includes(n!)) tongue = true;
          else cream = true;
        }
        color = point ? PAL.k : cream ? PAL.o : tongue ? PAL.r : undefined;
      } else {
        color = PAL[ch!];
      }
      if (!color) continue;
      if (mask) mask[y * w + x] = 1;
      if (ctx) {
        ctx.fillStyle = color;
        ctx.fillRect(x, y, 1, 1);
      }
    }
  }
  return c;
}

function mirror(src: HTMLCanvasElement): HTMLCanvasElement {
  const c = document.createElement("canvas");
  c.width = src.width;
  c.height = src.height;
  const ctx = c.getContext("2d");
  if (ctx) {
    ctx.translate(src.width, 0);
    ctx.scale(-1, 1);
    ctx.drawImage(src, 0, 0);
  }
  return c;
}

const built = new Map<PartName, HTMLCanvasElement>();
const builtFlipped = new Map<PartName, HTMLCanvasElement>();
/** Opaque pixels of each part (1 = drawn), for pixel-exact taps. */
const masks = new Map<PartName, { w: number; h: number; data: Uint8Array }>();

/** A part's canvas (built once, cached). */
export function part(name: PartName, flip = false): HTMLCanvasElement | null {
  let c = built.get(name);
  if (!c) {
    const rows = ART[name] as readonly string[] | undefined;
    if (!rows) return null;
    const w = Math.max(1, ...rows.map((r) => r.length));
    const h = Math.max(1, rows.length);
    const data = new Uint8Array(w * h);
    c = buildSprite(rows, data);
    built.set(name, c);
    masks.set(name, { w, h, data });
  }
  if (!flip) return c;
  let f = builtFlipped.get(name);
  if (!f) {
    f = mirror(c);
    builtFlipped.set(name, f);
  }
  return f;
}

/** Build every part up front (call once at init, so the first frame doesn't stutter). */
export function buildAllParts(): void {
  for (const name of Object.keys(ART) as PartName[]) part(name);
}

/**
 * Draw a stack of layers as one 32x32 frame whose top-left is (left, top). Flipped frames are
 * mirrored as a whole (each layer lands where its mirror image belongs).
 */
export function drawLayers(ctx: CanvasRenderingContext2D, left: number, top: number, layers: readonly Layer[], flip = false): void {
  for (const [name, dx, dy] of layers) {
    const c = part(name, flip);
    if (!c) continue;
    const x = flip ? FRAME - dx - c.width : dx;
    ctx.drawImage(c, Math.round(left + x), Math.round(top + dy));
  }
}

/**
 * Is frame pixel (fx, fy) covered by any of these layers (as drawn by drawLayers with the same
 * flip)? `slop` px of tolerance in every direction.
 */
export function opaqueAt(layers: readonly Layer[], flip: boolean, fx: number, fy: number, slop = 0): boolean {
  for (const [name, dx, dy] of layers) {
    if (!part(name)) continue;
    const m = masks.get(name);
    if (!m) continue;
    const x0 = flip ? FRAME - dx - m.w : dx;
    for (let oy = -slop; oy <= slop; oy++) {
      for (let ox = -slop; ox <= slop; ox++) {
        let lx = Math.floor(fx + ox) - x0;
        const ly = Math.floor(fy + oy) - dy;
        if (lx < 0 || ly < 0 || lx >= m.w || ly >= m.h) continue;
        if (flip) lx = m.w - 1 - lx;
        if (m.data[ly * m.w + lx]) return true;
      }
    }
  }
  return false;
}

/** Render layers into a fresh 32x32 canvas (for DOM icons). */
export function composite(layers: readonly Layer[]): HTMLCanvasElement {
  const c = document.createElement("canvas");
  c.width = FRAME;
  c.height = FRAME;
  const ctx = c.getContext("2d");
  if (ctx) drawLayers(ctx, 0, 0, layers);
  return c;
}

